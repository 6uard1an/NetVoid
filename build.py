"""Build (and optionally flash) with the Arduino ESP32 core's own compiler; no IDE or arduino-cli needed.
   python build.py            build only
   python build.py COM8       build and flash"""
import os, subprocess, sys, tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

VER, TC = "3.3.7", "2511"
HERE = Path(__file__).resolve().parent
PKG = Path(os.environ["LOCALAPPDATA"]) / "Arduino15/packages/esp32"
HW, SDK = PKG / "hardware/esp32" / VER, PKG / "tools/esp32-libs" / VER
BIN = PKG / "tools/esp-x32" / TC / "bin"
ESPTOOL = str(PKG / "tools/esptool_py/5.1.0/esptool.exe")
OUT = Path(tempfile.gettempdir()) / "esp32-proxy-build"
(OUT / "o").mkdir(parents=True, exist_ok=True)

LIBS = ["WiFi", "Network", "Preferences", "FS", "Hash", "SD", "SPI"] + (["LittleFS"] if "--sd-test" in sys.argv else [])
MEM = "dio_qspi"
defs = ["-DF_CPU=240000000L", "-DARDUINO=10819", "-DARDUINO_ESP32_DEV", "-DARDUINO_ARCH_ESP32", '-DARDUINO_BOARD="ESP32_DEV"',
        '-DARDUINO_VARIANT="esp32"', "-DARDUINO_PARTITION_default_8MB", '-DARDUINO_HOST_OS="windows"', '-DARDUINO_FQBN="esp32:esp32:esp32"',
        "-DESP32=ESP32", "-DCORE_DEBUG_LEVEL=0", "-DARDUINO_USB_CDC_ON_BOOT=0"] + (["-DSD_TEST"] if "--sd-test" in sys.argv else [])
inc = [f"@{SDK}/flags/defines", "-iprefix", f"{SDK}/include/", f"@{SDK}/flags/includes", f"-I{SDK}/{MEM}/include",
       f"-I{HW}/cores/esp32", f"-I{HW}/variants/esp32"] + [f"-I{HW}/libraries/{l}/src" for l in LIBS]

def run(cmd):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True, errors="replace")
    if r.returncode:
        sys.exit(f"FAILED: {cmd[0]} {cmd[-1]}\n{r.stdout[-4000:]}\n{r.stderr[-8000:]}")
    return r.stdout + r.stderr

def compile_one(src, name, core):
    obj = OUT / "o" / (name + ".o")
    hdrs = [p.stat().st_mtime for p in (HERE / "esp32-proxy").glob("*.h")] if not core else []
    if obj.exists() and obj.stat().st_mtime > max([src.stat().st_mtime] + hdrs):
        return obj
    ext = src.suffix.lower()
    flags, cc = {".c": ("c_flags", "gcc"), ".cpp": ("cpp_flags", "g++"), ".s": ("S_flags", "gcc")}[ext]
    x = ["-x", "assembler-with-cpp"] if ext == ".s" else []
    msg = run([BIN / f"xtensa-esp32-elf-{cc}.exe", "-c", *x, f"@{SDK}/flags/{flags}", "-Os" if core else "-O2", "-w" if core else "-Wall", *defs,
               *(["-DARDUINO_CORE_BUILD"] if core else []), *inc, src, "-o", obj])
    if not core and msg.strip(): print(msg)
    return obj

# The injected script is served compressed, so it fits in two packets.
import gzip
src = (HERE / "esp32-proxy/pages.h").read_text(encoding="utf8").split('HOOK_JS[] = R"~(')[1].split(')~"')[0]
gz = gzip.compress(src.encode(), 9, mtime=0)
hdr = "// Generated by build.py from HOOK_JS in pages.h\n#pragma once\n#include <stdint.h>\nstatic const uint8_t HOOK_GZ[] = {" + ",".join(map(str, gz)) + "};\n"
out = HERE / "esp32-proxy/hook_gz.h"
if not out.exists() or out.read_text() != hdr: out.write_text(hdr, newline="\n")

jobs = [(HERE / f"esp32-proxy/{n}.cpp", n, False) for n in ("proxy", "lowmem")]
for base in [HW / "cores/esp32"] + [HW / f"libraries/{l}/src" for l in LIBS]:
    for p in base.rglob("*"):
        if p.suffix.lower() in (".c", ".cpp", ".s"):
            jobs.append((p, "_".join(p.relative_to(HW).parts), True))
with ThreadPoolExecutor(os.cpu_count()) as ex:
    objs = list(ex.map(lambda j: compile_one(*j), jobs))

lib = OUT / "core.a"
lib.unlink(missing_ok=True)
rsp = OUT / "objs.txt"
rsp.write_text("\n".join(f'"{o.as_posix()}"' for o in objs[2:]))
run([BIN / "xtensa-esp32-elf-gcc-ar.exe", "cr", lib, f"@{rsp}"])
elf = OUT / "proxy.elf"
run([BIN / "xtensa-esp32-elf-g++.exe", f"-L{SDK}/lib", f"-L{SDK}/ld", f"-L{SDK}/{MEM}", "-Wl,--wrap=esp_panic_handler", "-Wl,--wrap=mbedtls_calloc", "-Wl,--wrap=mbedtls_zeroize_and_free", "-Wl,--wrap=tcp_alloc", "-Wl,--wrap=esp_wifi_init",
     "-Wl,--wrap=mbedtls_ssl_set_hostname", "-Wl,--wrap=mbedtls_ssl_handshake", f"@{SDK}/flags/ld_flags",
     f"@{SDK}/flags/ld_scripts", "-Wl,--start-group", objs[0], objs[1], lib, f"@{SDK}/flags/ld_libs", "-Wl,--end-group", "-Wl,-EL", "-o", elf])
img = ["--flash-mode", "dio", "--flash-freq", "40m", "--flash-size", "8MB"]
run([ESPTOOL, "--chip", "esp32", "elf2image", *img, "--elf-sha256-offset", "0xb0", "-o", OUT / "proxy.bin", elf])
run([ESPTOOL, "--chip", "esp32", "elf2image", *img, "-o", OUT / "boot.bin", SDK / "bin/bootloader_dio_40m.elf"])
run([HW / "tools/gen_esp32part.exe", "-q", HW / "tools/partitions/default_8MB.csv", OUT / "parts.bin"])
print(run([BIN / "xtensa-esp32-elf-size.exe", elf]))
print("image", (OUT / "proxy.bin").stat().st_size, "bytes")

# Bundle the four images for flashing from the Flipper (NetVoid app reads flash.txt off the SD card).
import shutil
FW = HERE / "firmware"
FW.mkdir(exist_ok=True)
bundle = [("0x1000", OUT / "boot.bin", "bootloader.bin"), ("0x8000", OUT / "parts.bin", "partitions.bin"),
          ("0xe000", HW / "tools/partitions/boot_app0.bin", "boot_app0.bin"), ("0x10000", OUT / "proxy.bin", "app.bin")]
for off, srcp, nm in bundle: shutil.copy(srcp, FW / nm)
(FW / "flash.txt").write_text("".join(f"{off} {nm}\n" for off, _, nm in bundle), newline="\n")
print("firmware bundle ->", FW, "(copy this folder to the Flipper SD: apps_data/esp_proxy/firmware)")
port = next((x for x in sys.argv[1:] if x.startswith("COM")), None)
if port:
    print(run([ESPTOOL, "--chip", "esp32", "--port", port, "--baud", "115200", "write-flash", "-z", *img, "0x1000", OUT / "boot.bin",
               "0x8000", OUT / "parts.bin", "0xe000", HW / "tools/partitions/boot_app0.bin", "0x10000", OUT / "proxy.bin"])[-500:])
